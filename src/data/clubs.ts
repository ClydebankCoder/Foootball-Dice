export const LEAGUE_NAMES: Record<Club['league'], string> = Object.fromEntries(
  LEAGUES.map((league) => [league.id, league.name]),
) as Record<Club['league'], string>;

const BY_ID = new Map(CLUBS.map((club) => [club.id, club]));

export function getClub(id: string): Club {
  const club = BY_ID.get(id);
  if (!club) throw new Error(`Unknown club: ${id}`);
  return club;
}

/** The clubs each division starts with in a brand new career. */
export function startingDivisions(): Record<Club['league'], string[]> {
  const divisions = {} as Record<Club['league'], string[]>;
  for (const league of LEAGUES) {
    divisions[league.id] = CLUBS.filter((club) => club.league === league.id).map(
      (club) => club.id,
    );
  }
  return divisions;
}

/** Sanity check used by the tests: every division must be the right size. */
export function divisionSizesMatch(): boolean {
  return LEAGUES.every(
    (league) => CLUBS.filter((c) => c.league === league.id).length === getLeague(league.id).size,
  );
}
